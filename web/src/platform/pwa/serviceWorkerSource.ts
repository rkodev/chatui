import {
  CACHEABLE_EXACT_PATHS,
  CACHEABLE_PATH_PREFIXES,
  NEVER_CACHE_PATHS,
  SHELL_PATH,
} from './cachePolicy.ts'

export interface ServiceWorkerSourceOptions {
  /** Versioned cache name, for example `chatui-shell-1a2b3c4d`. */
  cacheName: string
  /** Root-relative paths to precache. Already filtered by the build. */
  precache: readonly string[]
}

/**
 * Build the service worker source emitted by the Vite plugin.
 *
 * The worker is intentionally hand-written instead of pulling in Workbox or a
 * PWA plugin. It has one job: precache the shell and hashed assets, serve the
 * shell for offline navigations, and pass every other request through without
 * touching the Cache API. The allowlist constants are injected from
 * `cachePolicy.ts` so the worker and the tests cannot drift.
 */
export function createServiceWorkerSource({
  cacheName,
  precache,
}: ServiceWorkerSourceOptions): string {
  return `/* Generated by web/vite.config.ts. Do not edit by hand. */
const CACHE_NAME = ${JSON.stringify(cacheName)};
const PRECACHE = ${JSON.stringify(precache)};
const SHELL = ${JSON.stringify(SHELL_PATH)};
const CACHEABLE_EXACT_PATHS = ${JSON.stringify(CACHEABLE_EXACT_PATHS)};
const CACHEABLE_PATH_PREFIXES = ${JSON.stringify(CACHEABLE_PATH_PREFIXES)};
const NEVER_CACHE_PATHS = ${JSON.stringify(NEVER_CACHE_PATHS)};

function isNeverCachePath(pathname) {
  return NEVER_CACHE_PATHS.some(function (path) {
    return pathname === path || pathname.startsWith(path);
  });
}

function isCacheablePath(pathname) {
  if (isNeverCachePath(pathname)) {
    return false;
  }

  return (
    CACHEABLE_EXACT_PATHS.indexOf(pathname) !== -1 ||
    CACHEABLE_PATH_PREFIXES.some(function (prefix) {
      return pathname.startsWith(prefix);
    })
  );
}

self.addEventListener('install', function (event) {
  event.waitUntil(
    caches.open(CACHE_NAME).then(function (cache) {
      return cache.addAll(PRECACHE);
    }),
  );
});

self.addEventListener('activate', function (event) {
  event.waitUntil(
    (async function () {
      const keys = await caches.keys();
      await Promise.all(
        keys
          .filter(function (key) {
            return key.startsWith('chatui-shell-') && key !== CACHE_NAME;
          })
          .map(function (key) {
            return caches.delete(key);
          }),
      );
      await self.clients.claim();
    })(),
  );
});

self.addEventListener('message', function (event) {
  if (event.data && event.data.type === 'SKIP_WAITING') {
    self.skipWaiting();
  }
});

self.addEventListener('fetch', function (event) {
  const request = event.request;

  if (request.method !== 'GET') {
    return;
  }

  const url = new URL(request.url);

  if (url.origin !== self.location.origin) {
    return;
  }

  if (isNeverCachePath(url.pathname)) {
    return;
  }

  if (request.mode === 'navigate') {
    event.respondWith(
      (async function () {
        try {
          const response = await fetch(request);

          if (response.ok) {
            return response;
          }
        } catch {
          // Fall through to the cached shell when the network is unavailable.
        }

        const cache = await caches.open(CACHE_NAME);
        const cached = await cache.match(SHELL);

        return cached || Response.error();
      })(),
    );
    return;
  }

  if (!isCacheablePath(url.pathname)) {
    return;
  }

  event.respondWith(
    (async function () {
      const cache = await caches.open(CACHE_NAME);
      const cached = await cache.match(request);

      if (cached) {
        return cached;
      }

      const response = await fetch(request);

      if (response.ok) {
        await cache.put(request, response.clone());
      }

      return response;
    })(),
  );
});
`
}
