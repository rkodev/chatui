import java.security.MessageDigest
import java.util.Base64

data class BaselineImage(
    val name: String,
    val mimeType: String,
    val width: Int,
    val height: Int,
    val dataBase64: String,
) {
    val bytes: ByteArray
        get() = Base64.getDecoder().decode(dataBase64)

    val sha256: String
        get() = baselineSha256(bytes)
}

fun baselineSha256(bytes: ByteArray): String =
    MessageDigest.getInstance("SHA-256").digest(bytes).joinToString("") { "%02x".format(it) }

